const PHP_NUMBER = new Intl.NumberFormat("en-PH", {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2
});

function normalizeDate(value) {
  if (!value || value === "—") return "";
  const match = String(value).match(/^\d{4}-\d{2}-\d{2}/);
  if (match) return match[0];
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? "" : date.toISOString().slice(0, 10);
}

function displayDate(value) {
  const normalized = normalizeDate(value);
  if (!normalized) return "—";
  return new Intl.DateTimeFormat("en-PH", {
    year: "numeric",
    month: "short",
    day: "numeric"
  }).format(new Date(`${normalized}T00:00:00`));
}

export function currentMonthValue() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}`;
}

export function voucherMonth(value) {
  return normalizeDate(value).slice(0, 7);
}

export function getVoucherReportMonths(vouchers) {
  const months = [...new Set(vouchers
    .filter((voucher) => !voucher.deletedAt)
    .map((voucher) => voucherMonth(voucher.voucherDate))
    .filter(Boolean))]
    .sort((first, second) => second.localeCompare(first));
  return months.length ? months : [currentMonthValue()];
}

export function formatReportMonth(value) {
  if (!/^\d{4}-\d{2}$/.test(value || "")) return "Unknown month";
  return new Intl.DateTimeFormat("en-PH", { year: "numeric", month: "long" })
    .format(new Date(`${value}-01T00:00:00`));
}

export function monthDateRange(value) {
  const [year, month] = String(value).split("-").map(Number);
  const lastDay = new Date(year, month, 0).getDate();
  return {
    from: `${value}-01`,
    to: `${value}-${String(lastDay).padStart(2, "0")}`
  };
}

export function createMonthlyVoucherRows(vouchers, month) {
  return vouchers
    .filter((voucher) => !voucher.deletedAt && voucherMonth(voucher.voucherDate) === month)
    .sort((first, second) => {
      const dateOrder = normalizeDate(first.voucherDate).localeCompare(normalizeDate(second.voucherDate));
      return dateOrder || String(first.voucherNumber || "").localeCompare(String(second.voucherNumber || ""));
    })
    .map((voucher) => ({
      id: voucher.id,
      voucherNumber: voucher.voucherNumber || "—",
      supplierName: voucher.supplierName || "—",
      purchaseOrder: voucher.purchaseOrder || "—",
      salesInvoice: voucher.salesInvoice || "—",
      voucherDate: displayDate(voucher.voucherDate),
      paymentType: String(voucher.bankName || "—").toUpperCase(),
      chequeNumber: voucher.chequeNumber || "—",
      amount: Number(voucher.amountApplied || 0),
      status: voucher.status || "Draft"
    }));
}

export function monthlyVoucherTotal(rows) {
  return rows.reduce((total, row) => total + Number(row.amount || 0), 0);
}

function pdfValue(value) {
  return String(value ?? "—").replaceAll("—", "-");
}

export async function exportMonthlyVoucherReportPdf(rows, month, generatedBy) {
  if (!rows.length) throw new Error("There are no voucher records to download for this month.");

  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 8;
  const columns = [
    { label: "Voucher #", key: "voucherNumber", width: 18 },
    { label: "Supplier", key: "supplierName", width: 35 },
    { label: "P.O. #", key: "purchaseOrder", width: 24 },
    { label: "S.I. #", key: "salesInvoice", width: 24 },
    { label: "Voucher Date", key: "voucherDate", width: 23 },
    { label: "Type of Payment", key: "paymentType", width: 28 },
    { label: "Cheque No.", key: "chequeNumber", width: 24 },
    { label: "Amount", key: "amount", width: 26, money: true },
    { label: "Status", key: "status", width: 20 }
  ];
  const tableWidth = pageWidth - margin * 2;
  const totalWeight = columns.reduce((sum, column) => sum + column.width, 0);
  const widths = columns.map((column) => tableWidth * column.width / totalWeight);

  function drawHeading() {
    doc.setTextColor(8, 8, 8);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(15);
    doc.text("ILLUMINUX GENERAL MERCH CO.", pageWidth / 2, 11, { align: "center" });
    doc.setFontSize(8);
    doc.text("Blk. 4, Queenstown 1 Heights, Brgy. San Luis, Antipolo City", pageWidth / 2, 16, { align: "center" });
    doc.setFontSize(12);
    doc.text(`MONTHLY VOUCHER REPORT — ${formatReportMonth(month).toUpperCase()}`, pageWidth / 2, 23, { align: "center" });
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.text(`Generated by: ${generatedBy || "Illuminux user"}`, margin, 29);
    doc.text(`${rows.length} voucher(s)`, pageWidth - margin, 29, { align: "right" });
  }

  function drawTableHeader(y) {
    let x = margin;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(6.5);
    columns.forEach((column, index) => {
      doc.setFillColor(255, 173, 50);
      doc.setDrawColor(8, 8, 8);
      doc.rect(x, y, widths[index], 10, "FD");
      doc.text(doc.splitTextToSize(column.label, widths[index] - 2), x + widths[index] / 2, y + 4, { align: "center" });
      x += widths[index];
    });
    return y + 10;
  }

  drawHeading();
  let y = drawTableHeader(33);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(6.3);

  rows.forEach((row) => {
    const values = columns.map((column) => column.money
      ? `PHP ${PHP_NUMBER.format(Number(row[column.key] || 0))}`
      : pdfValue(row[column.key]));
    const lines = values.map((value, index) => doc.splitTextToSize(value, widths[index] - 2.5));
    const rowHeight = Math.max(8, Math.max(...lines.map((line) => line.length)) * 3.2 + 2);

    if (y + rowHeight > pageHeight - 16) {
      doc.addPage();
      drawHeading();
      y = drawTableHeader(33);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(6.3);
    }

    let x = margin;
    columns.forEach((column, index) => {
      doc.setFillColor(255, 255, 255);
      doc.setDrawColor(8, 8, 8);
      doc.rect(x, y, widths[index], rowHeight, "FD");
      doc.text(lines[index], column.money ? x + widths[index] - 1.3 : x + 1.3, y + 4, {
        align: column.money ? "right" : "left"
      });
      x += widths[index];
    });
    y += rowHeight;
  });

  if (y + 10 > pageHeight - 8) {
    doc.addPage();
    drawHeading();
    y = 35;
  }
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8);
  doc.text(`Monthly Total: PHP ${PHP_NUMBER.format(monthlyVoucherTotal(rows))}`, pageWidth - margin, y + 7, { align: "right" });
  doc.save(`illuminux-monthly-vouchers-${month}.pdf`);
}
